export function getGroovedFittingRecordId(record: Pick<GroovedFittingRecord, "productId" | "specification" | "pressureRatingMpa">) {
  return [record.productId, record.specification, record.pressureRatingMpa].join("__");
}

export function findGroovedFittingRecord(
  fittingTypeId: string,
  specification: string,
  pressureRatingMpa: number,
) {
  return groovedFittingRecords.find(
    (record) =>
      record.productId === fittingTypeId &&
      record.specification === specification &&
      record.pressureRatingMpa === pressureRatingMpa,
  );
}

export function getFirstGroovedFittingRecord(fittingTypeId?: string) {
  return groovedFittingRecords.find((record) => !fittingTypeId || record.productId === fittingTypeId) ?? null;
}
